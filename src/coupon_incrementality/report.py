"""Write reports/RESULTS.md: every headline number, straight from the result files."""

from __future__ import annotations

from .config import ROOT, load_result

OUT = ROOT / "reports" / "RESULTS.md"


def money(value: float, digits: int = 2) -> str:
    return f"{'−' if value < 0 else ''}${abs(value):,.{digits}f}"


def ci(block: dict, digits: int = 2, pct: bool = False) -> str:
    if pct:
        low, high = block["lift_pct_low"], block["lift_pct_high"]
        return f"{block['lift_pct']:+.1f}% ({low:+.1f}% to {high:+.1f}%)".replace("-", "−")
    low, high = money(block["ci_low"], digits), money(block["ci_high"], digits)
    return f"{money(block['estimate'], digits)} ({low} to {high})"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def build() -> str:
    naive, dml, td, es, bc, dec, het, pol, rob = (
        load_result(n)
        for n in (
            "naive", "dml", "triple_diff", "event_study", "dml_bc", "decomposition",
            "heterogeneity", "policy", "robustness",
        )
    )  # fmt: skip
    program, a, b = dec["program"], naive["comparison"]["A"], naive["comparison"]["BC"]
    parts = [
        "# Results\n",
        "Generated by `make report` from `reports/results/*.json`. Do not edit by hand.\n",
    ]

    parts.append("## Headline: gross profit per $1 of coupon spend\n")
    parts.append(
        table(
            ["Step", "Per $1 of coupon spend"],
            [
                ["Dashboard (naive lift)", money(program["naive"]["estimate"])],
                ["Targeting bias", money(program["targeting_bias"]["estimate"])],
                ["Causal lift during campaign", money(program["causal"]["estimate"])],
                ["After-campaign effect", money(program["after"]["estimate"])],
                ["Cannibalisation", money(program["cannibalisation"]["estimate"])],
                ["Halo", money(program["halo"]["estimate"])],
                ["**True incremental profit**", f"**{ci(program['true'])}**"],
            ],
        )
    )
    parts.append(
        f"\nShare of the dashboard number that is real: "
        f"{program['share_of_naive_that_is_real_pct']:.0f}%. "
        f"Coupon spend analysed: {money(program['coupon_spend'], 0)} "
        f"(margin {dec['assumptions']['margin']:.1%}, mailing cost "
        f"{money(dec['assumptions']['mail_cost_per_household_campaign'])} per household-campaign).\n"
    )
    parts.append(
        table(
            ["Campaign family", "Recipient-campaigns", "Coupon $ redeemed each", "True profit per $1"],
            [
                ["Type A", f"{dec['recipients_and_costs']['A']['n']:,}", money(dec["recipients_and_costs"]["A"]["coupon_dollars"]), ci(dec["type_a"]["true"])],
                ["Type B/C", f"{dec['recipients_and_costs']['BC']['n']:,}", money(dec["recipients_and_costs"]["BC"]["coupon_dollars"]), ci(dec["type_bc"]["true"])],
                ["Type B/C, no halo credited", "", "", ci(dec["type_bc_without_halo"]["true"])],
            ],
        )
    )  # fmt: skip

    parts.append("\n## Sensitivity to the two assumptions\n")
    grid = dec["sensitivity"]
    mails = sorted({g["mail_cost"] for g in grid})
    rows = []
    for margin in sorted({g["margin"] for g in grid}):
        cells = [
            next(g for g in grid if g["margin"] == margin and g["mail_cost"] == m) for m in mails
        ]
        rows.append(
            [f"{margin:.1%}"]
            + [f"{money(c['true'])} (dashboard {money(c['naive'])})" for c in cells]
        )
    parts.append(table(["Gross margin"] + [f"Mailing cost {money(m)}" for m in mails], rows))

    parts.append("\n## Phase 2: naive baseline\n")
    parts.append(
        table(
            ["Comparison (weekly in-store spend)", "Type A", "Type B/C"],
            [
                ["Recipients", money(a["recipients_weekly_spend"]), money(b["recipients_weekly_spend"])],
                ["Non-recipients", money(a["non_recipients_weekly_spend"]), money(b["non_recipients_weekly_spend"])],
                ["Naive lift", f"{a['recipient_lift_pct']:+.0f}%", f"{b['recipient_lift_pct']:+.0f}%"],
                ["Redeemers", money(a["redeemers_weekly_spend"]), money(b["redeemers_weekly_spend"])],
                ["Non-redeemers", money(a["non_redeemers_weekly_spend"]), money(b["non_redeemers_weekly_spend"])],
                ["Naive lift (redeemers)", f"{a['redeemer_lift_pct']:+.0f}%", f"{b['redeemer_lift_pct']:+.0f}%"],
            ],
        )
    )  # fmt: skip
    ra = naive["redemption_attribution"]
    parts.append(
        f"\nType B/C covered products only: recipients {money(td['naive']['recipients_weekly_covered_spend'])} "
        f"vs non-recipients {money(td['naive']['non_recipients_weekly_covered_spend'])} per week "
        f"(naive lift {td['naive']['lift_pct']:+.0f}%). Redemption attribution: {ra['matched_redemptions']:,} "
        f"matched redemptions, {money(ra['sales_per_coupon_dollar'])} of sales per coupon dollar.\n"
    )

    parts.append("## Phase 3: three causal designs\n")
    during = dml["during"]
    base = dml["recipient_mean_spend"]
    lift = lambda block: f"{100 * block['estimate'] / base:+.1f}%"  # noqa: E731
    main_es = es["main"]
    parts.append(
        table(
            ["Design", "Effect on weekly spend (95% CI)", "As % of recipients' spend"],
            [
                ["3a. Double ML, effect on recipients (primary)", ci(during["att"]), lift(during["att"])],
                ["3a. Double ML, partially linear", ci(during["plr"]), lift(during["plr"])],
                ["3a. Double ML, average effect", ci(during["ate"]), lift(during["ate"])],
                ["3a. Double ML, no trimming", ci(during["att_untrimmed"]), lift(during["att_untrimmed"])],
                ["3a. Double ML, outcome in levels", ci(during["att_levels"]), lift(during["att_levels"])],
                ["3a. Own AIPW engine (cross-check)", ci(dml["aipw_cross_check"]), lift(dml["aipw_cross_check"])],
                ["3c. Event study", ci(main_es["during"]), lift(main_es["during"])],
                ["3c. Event study, drift removed", ci(main_es["detrended"]["during"]), lift(main_es["detrended"]["during"])],
                ["3c. Event study, later-treated controls only", ci(es["eventually_treated_only"]["during"]), lift(es["eventually_treated_only"]["during"])],
                ["3c. Event study, covariate-adjusted (rejected)", ci(es["covariate_adjusted"]["during"]), lift(es["covariate_adjusted"]["during"])],
            ],
        )
    )  # fmt: skip
    o = dml["overlap"]
    parts.append(
        f"\nDouble ML: {dml['n_rows']:,} household-campaigns, {dml['n_features']} features; "
        f"{o['n_trimmed']:,} ({o['share_trimmed']:.0%}) trimmed for lack of overlap, keeping "
        f"{o['recipients_kept']:,} recipient rows ({o['share_recipients_kept']:.0%}). Recipients' mean weekly "
        f"spend {money(base)}; campaigns ran {dml['mean_campaign_weeks']:.1f} weeks on average. "
        f"After-campaign effect (4 weeks, campaigns {dml['post']['campaigns']}): {ci(dml['post']['att'])}.\n"
    )
    parts.append(
        f"Event study: {es['n_households']:,} households, {es['n_cohorts']} cohorts, "
        f"{es['n_never_treated']:,} never treated. Pre-trend joint test p = "
        f"{main_es['pretrend_test']['p_value']:.2f}; drift {money(main_es['detrended']['drift_per_week'])} per week "
        f"(SE {main_es['detrended']['drift_se']:.2f}). Weeks 5-8: {ci(main_es['after'])}. "
        f"Covariate-adjusted pre-trend test p = {es['covariate_adjusted']['pretrend_test']['p_value']:.1g}.\n"
    )
    m = td["main"]
    parts.append(
        table(
            ["3b. Triple difference (Type B/C)", "Lift (95% CI)", "p"],
            [[label, ci(m[key], pct=True), f"{m[key]['p_value']:.2f}"] for label, key in [
                ("Covered products, during", "covered_during"),
                ("Covered products, 8 weeks after", "covered_post"),
                ("Sibling products, during", "sibling_during"),
                ("Sibling products, after", "sibling_post"),
                ("Placebo products, during", "placebo_during"),
                ("Placebo products, after", "placebo_post"),
            ]],
        )
    )  # fmt: skip
    ols = td["ols_levels"]
    parts.append(
        f"\n{td['n_campaigns']} campaigns, {td['dollars']['n_recipient_campaigns']:,} recipient-campaigns, "
        f"{m['n_obs']:,} informative cells. Pre-trend joint test p = {td['event_study']['pretrend_test']['p_value']:.2f}. "
        f"Display share coefficient {m['display_share']['coef']:.2f} (p = {m['display_share']['p_value']:.2f}). "
        f"OLS in levels (not used): covered {money(ols['covered_during']['coef'])}, "
        f"placebo {money(ols['placebo_during']['coef'])} per week.\n"
    )

    parts.append("## Phase 4: dollars per recipient household per campaign\n")
    d = td["dollars"]
    parts.append(
        table(
            ["Component (Type B/C)", "Source", "Dollars of sales (95% CI)"],
            [
                ["Covered products, during", "Triple difference", ci({"estimate": d["covered_during"]["dollars_per_recipient"]} | d["covered_during"])],
                ["Covered products, after", "Triple difference", ci({"estimate": d["covered_post"]["dollars_per_recipient"]} | d["covered_post"])],
                ["Sibling products, during", "Triple difference", ci({"estimate": d["sibling_during"]["dollars_per_recipient"]} | d["sibling_during"])],
                ["Rest of store, during (halo)", "Double ML", ci(bc["during"]["rest"])],
                ["Covered products, during", "Double ML (second opinion)", ci(bc["during"]["covered"])],
                ["Sibling products, during", "Double ML (second opinion)", ci(bc["during"]["sibling"])],
            ],
        )
    )  # fmt: skip
    halo = td["halo_did"]
    parts.append(
        f"\nHalo by difference-in-differences (rejected): {halo['pooled']['during']['lift_pct']:+.1f}% "
        f"(p = {halo['pooled']['during']['p_value']:.3f}).\n"
    )
    parts.append(
        table(
            ["Type A under each design", "True profit per $1 (95% CI)"],
            [[name, ci(block)] for name, block in dec["type_a_by_design"].items()],
        )
    )

    parts.append("\n## Phase 5: who responds\n")
    g, blp = het["gates"], het["blp"]
    parts.append(
        table(
            ["Fifth (by predicted response)"] + [str(i) for i in g["group"]],
            [["Measured effect on weekly spend"] + [f"{money(e)} (SE {s:.2f})" for e, s in zip(g["effect"], g["se"], strict=True)]],
        )
    )  # fmt: skip
    parts.append(
        f"\nGATES top minus bottom: {money(g['top_minus_bottom'])} (SE {g['top_minus_bottom_se']:.2f}, "
        f"p = {g['top_minus_bottom_p_value']:.2f}). BLP slope {blp['slope']:.2f} (SE {blp['slope_se']:.2f}, "
        f"one-sided p = {blp['slope_p_value_one_sided']:.2f}); average effect {money(blp['average_effect'])} "
        f"(SE {blp['average_effect_se']:.2f}).\n"
    )
    parts.append(
        table(
            ["Trait", "Bottom fifth", "Top fifth"],
            [
                [k, f"{v['bottom_fifth']:.2f}", f"{v['top_fifth']:.2f}"]
                for k, v in het["profile"].items()
            ],
        )
    )

    parts.append("\n## Phase 6: targeting policies (Type A, held-out households)\n")
    rows = []
    for name, p in pol["base"].items():
        rows.append([
            name, f"{p['mailers']:,.0f}", ci(p["profit"], 0), money(p["gross_profit_per_cost_dollar"]),
            "" if name.startswith("Retailer") else ci(p["gain_vs_actual"], 0),
        ])  # fmt: skip
    parts.append(
        table(
            [
                "Policy",
                "Mailers",
                "Incremental profit (95% CI)",
                "Per $1",
                "Gain vs. actual (95% CI)",
            ],
            rows,
        )
    )

    parts.append("\n## Phase 7: stress tests\n")
    pd_, sc, hc = rob["placebo_dates"], rob["single_campaign"], rob["hidden_confounding"]
    parts.append(
        table(
            ["Test", "Result"],
            [
                ["Placebo dates, Type A double ML", ci(pd_["dml_type_a"]) + " per week"],
                ["Placebo dates, triple difference (covered)", ci(pd_["triple_diff_type_bc"]["covered_during"], pct=True) + f", p = {pd_['triple_diff_type_bc']['covered_during']['p_value']:.1g}"],
                ["Placebo products, during", ci(rob["placebo_products"]["placebo_during"], pct=True)],
                ["Triple difference, 4-week baseline", ci(rob["short_baseline_triple_diff"]["covered_during"], pct=True)],
                ["One campaign at a time, Type A double ML", ci(sc["dml_type_a"]) + f" per week ({sc['dml_type_a']['n_recipient_rows']:,} recipient rows)"],
                ["One campaign at a time, triple difference", ci(sc["triple_diff_type_bc"]["covered_during"], pct=True) + f" ({sc['triple_diff_type_bc']['n_recipient_campaigns']} recipient-campaigns)"],
                ["Robustness value, double ML", f"{hc['double_ml']['robustness_value_pct']:.1f}%"],
                ["Robustness value, linear model (sensemakr)", f"{hc['sensemakr_ols']['robustness_value_pct']:.1f}% (to lose significance: {hc['sensemakr_ols']['robustness_value_ci_pct']:.1f}%)"],
            ],
        )
    )  # fmt: skip
    bench = hc["double_ml"]["benchmarks"]
    parts.append(
        "\n"
        + table(
            ["If we had not observed...", "Features", "Estimate would move by"],
            [[k, v["n_features"], money(v["estimate_shift"])] for k, v in bench.items()],
        )
    )
    sm = hc["sensemakr_ols"]
    rows = [
        [f"{k}x {name}", ci({"estimate": b_["adjusted_estimate"], "ci_low": b_["adjusted_ci_low"], "ci_high": b_["adjusted_ci_high"]})]
        for name, bounds in sm["bounds"].items()
        for k, b_ in zip((1, 2, 3), bounds, strict=True)
    ]  # fmt: skip
    parts.append(
        f"\nLinear model estimate {money(sm['estimate'])} (SE {sm['se']:.2f}). "
        "Worst case if a hidden confounder were as strong as:\n\n"
        + table(["Hidden confounder", "Adjusted estimate (95% CI)"], rows)
    )
    return "\n".join(parts) + "\n"


def run() -> None:
    OUT.write_text(build())
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    run()
